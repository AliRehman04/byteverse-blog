import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const source = readFileSync(new URL('../src/lib/seo-title.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exports = {};
new Function('exports', compiled)(exports);
const { analyzeTitle, buildFullTitle, graphemes, hasLiteralPhrase, layoutTitle, titleTag, previewAddress, titleExamples } = exports;
const draft = { title: 'JSON Formatter', brand: 'ByteVerse', keyword: 'json formatter', separator: ' | ' };
assert.equal(buildFullTitle(draft), 'JSON Formatter | ByteVerse');
assert.equal(buildFullTitle({ ...draft, title: ' \n\t ' }), '');
assert.equal(buildFullTitle({ ...draft, brand: '', title: ' A   tidy\n title ' }), 'A tidy title');
assert.equal(analyzeTitle(draft).characters, 26);
assert.equal(analyzeTitle(draft).coreCharacters, 14);
assert.equal(analyzeTitle(draft).keywordMatch, true);
assert.equal(Object.hasOwn(analyzeTitle(draft), 'score'), false);
assert.equal(analyzeTitle({ ...draft, keyword: '' }).keywordMatch, null);
assert.equal(analyzeTitle({ ...draft, title: 'Unrelated', brand: 'JSON Formatter' }).keywordMatch, false);
assert.equal(analyzeTitle({ ...draft, title: 'JSON Formatter | ByteVerse' }).duplicateBrand, true);
assert.equal(analyzeTitle({ ...draft, title: 'SEO seo SEO', brand: '' }).repeated[0], 'seo');
assert.equal(analyzeTitle({ ...draft, title: 'the the the', brand: '' }).repeated.length, 0);
assert.equal(analyzeTitle({ ...draft, title: 'Home' }).checks[0].status, 'review');
assert.equal(graphemes('👩‍💻').length, 1);
assert.equal(graphemes('e\u0301').length, 1);
assert.equal(analyzeTitle({ ...draft, title: '👩‍💻 Tips', brand: '' }).characters, 6);
assert.equal(hasLiteralPhrase('Resources for SEO teams', 'seo'), true);
assert.equal(hasLiteralPhrase('Roseology', 'seo'), false);
assert.equal(hasLiteralPhrase('C++ Guide', 'C++'), true);
assert.equal(hasLiteralPhrase('C# Guide', 'C++'), false);
assert.equal(hasLiteralPhrase('Café Guide', 'Cafe\u0301'), true);
assert.equal(hasLiteralPhrase('نیا عنوان لکھیں', 'عنوان'), true);
assert.equal(hasLiteralPhrase('Guide [.*] examples', '[.*]'), true);
assert.equal(hasLiteralPhrase('abc', ''), false);

const measure = text => graphemes(text).length * 10;
assert.deepEqual(layoutTitle('', 50, 1, measure), { lines: [], truncated: false, fullWidth: 0 });
assert.deepEqual(layoutTitle('Hello', 50, 1, measure), { lines: ['Hello'], truncated: false, fullWidth: 50 });
assert.deepEqual(layoutTitle('Hello world', 60, 1, measure).lines, ['Hello…']);
assert.deepEqual(layoutTitle('Hello world', 60, 2, measure).lines, ['Hello', 'world']);
assert.equal(layoutTitle('Hello world', 60, 2, measure).truncated, false);
assert.equal(layoutTitle('Hello world again', 60, 2, measure).truncated, true);
assert.equal(layoutTitle('IIIIIIIIII', 100, 1, text => text.length * 3).truncated, false);
assert.equal(layoutTitle('WWWWWWWWWW', 100, 1, text => text.length * 20).truncated, true);
assert.deepEqual(layoutTitle('👩‍💻👩‍💻👩‍💻👩‍💻', 30, 1, measure).lines, ['👩‍💻👩‍💻…']);
assert.deepEqual(layoutTitle('longwordwithoutspaces', 30, 2, measure).lines, ['lon', 'gw…']);
assert.deepEqual(layoutTitle('hello', 0, 1, measure).lines, []);
assert.deepEqual(layoutTitle('hello', 1, 1, measure).lines, []);
for (const text of ['Hello world again', '漢字漢字漢字漢字', 'A 👩‍💻 great guide', 'A     long\n title']) {
  const result = layoutTitle(text, 50, 2, measure);
  assert(result.lines.length <= 2);
  assert(result.lines.every(line => measure(line) <= 50));
}
assert.equal(titleTag({ ...draft, title: '<script>"A&B"</script>', brand: '' }), '<title>&lt;script&gt;&quot;A&amp;B&quot;&lt;/script&gt;</title>');
assert.equal(titleTag({ ...draft, title: '' }), '');
assert.equal(previewAddress('javascript:alert(1)').valid, false);
assert.equal(previewAddress('https://name:pass@example.com/').valid, false);
assert.deepEqual(previewAddress('https://example.com/tools/title?secret=not-displayed#fragment'), { host: 'example.com', path: '/tools/title', valid: true });
assert.equal(previewAddress('').valid, true);
assert.equal(titleExamples.length, 4);
console.log('PASS: title composition, Unicode, phrase boundaries, repetition, pixel layout, brand inclusion, safe HTML and inert URL preview.');