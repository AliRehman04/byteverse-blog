function buildClusterBlock(links) {
  return [
    "## Keep Learning in This Blogging SEO Cluster",
    "",
    "If you are building blog traffic from scratch, read these next:",
    "",
    ...links.map(([label, url]) => `- [${label}](${url})`),
    "",
  ].join("\n");
}

function upsertClusterBlock(content, links) {
  const block = buildClusterBlock(links).trimEnd();
  const pattern = /## Keep Learning in This Blogging SEO Cluster\n\n[\s\S]*?(?=\n## )/;
  if (pattern.test(content)) return content.replace(pattern, block);

  const firstHeading = content.indexOf("\n\n## ");
  if (firstHeading === -1) return `${content.trim()}\n\n${block}\n`;
  return `${content.slice(0, firstHeading)}\n\n${block}${content.slice(firstHeading + 2)}`;
}

